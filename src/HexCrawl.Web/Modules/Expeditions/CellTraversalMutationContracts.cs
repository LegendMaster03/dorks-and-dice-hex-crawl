using HexCrawl.Domain.Runtime;
using HexCrawl.Domain.Spatial;
using HexCrawl.Application;

namespace HexCrawl.Web.Api;

/// <summary>
/// Explicit versioned API surface for existing cell expeditions. These
/// contracts are intentionally separate from the legacy six-direction route.
/// An isolated cell-only start path is enabled; legacy browser workbench remains gated.
/// </summary>
public sealed record StartCellExpeditionRequest(
    string Name,
    Guid? ProcedureId,
    int? ProcedureRevision,
    PeriodicCellAddress StartCell,
    string PresentationKey = "dm-controlled",
    string? PresetKey = null)
{
    public ProcedureStartSelection Selection()
    {
        if (string.IsNullOrWhiteSpace(Name))
            throw new InvalidOperationException("Expedition name is required.");
        if (string.IsNullOrWhiteSpace(PresentationKey))
            throw new InvalidOperationException("Cell starts require a valid presentation policy key.");
        // The optional preset key selects the three executable geometric
        // recipes only. An existing saved revision is never silently upgraded.
        var selection = new ProcedureStartSelection(
            PresetKey: PresetKey, ProcedureId: ProcedureId,
            ProcedureRevision: ProcedureRevision);
        selection.Validate();
        return selection;
    }
}

public sealed record AdvanceCellWatchRequest(
    long ExpectedVersion,
    CellWatchTravelPlan Plan,
    CellWatchAdvanceInputs Inputs)
{
    public void Validate()
    {
        if (ExpectedVersion <= 0)
            throw new InvalidOperationException("An expected expedition version is required.");
        ArgumentNullException.ThrowIfNull(Plan);
        ArgumentNullException.ThrowIfNull(Inputs);
        ArgumentNullException.ThrowIfNull(Inputs.Travel);
        ValidateClientProvenance(Inputs.Travel.Provenance);
        if (Inputs.DmOverrideNote is { Length: > 2000 })
            throw new InvalidOperationException("DM override note exceeds 2000 characters.");
        if (Inputs.Navigation is { } nav
            && !(nav.Outcome == NavigationCheckOutcome.NotRequired
                && nav.Provenance.Source == ResolutionSource.ProcedureDefault))
            ValidateClientProvenance(nav.Provenance);
        // ResolvedEncounter.None is an inert procedure sentinel, not a
        // client assertion that an automatic roll or default check occurred.
        // All triggered outcomes still require human/external provenance.
        if (Inputs.Encounter is { } encounter
            && !(encounter.Kind == EncounterOutcomeKind.None
                && encounter.Provenance.Source == ResolutionSource.ProcedureDefault))
            ValidateClientProvenance(encounter.Provenance);
        if (Inputs.BoundaryDecision is { } boundary) ValidateClientProvenance(boundary.Provenance);
    }

    internal static void ValidateClientProvenance(ResolutionProvenance provenance)
    {
        ArgumentNullException.ThrowIfNull(provenance);
        // Both default resolutions and automatic rolls are generated by
        // procedure/server policy. A client cannot claim either authority.
        if (provenance.Source is ResolutionSource.AutomaticRoll
            or ResolutionSource.ProcedureDefault)
            throw new InvalidOperationException(
                "Server-issued resolution provenance cannot be supplied by the client.");
        if (provenance.Source is not (
            ResolutionSource.ManualRoll or ResolutionSource.ExternalSystem
            or ResolutionSource.DmOverride))
            throw new InvalidOperationException("Unknown client resolution provenance source.");
        if (provenance.Note is { Length: > 2000 })
            throw new InvalidOperationException(
                "Resolution provenance note exceeds 2000 characters.");
    }
}

public sealed record ResolveCellCourseRequest(
    long ExpectedVersion,
    CellCourseDecision Decision)
{
    public void Validate()
    {
        if (ExpectedVersion <= 0)
            throw new InvalidOperationException("An expected expedition version is required.");
        ArgumentNullException.ThrowIfNull(Decision);
        AdvanceCellWatchRequest.ValidateClientProvenance(Decision.Provenance);
    }
}

/// <summary>Explicit qualified reposition, never inferred travel.</summary>
public sealed record RepositionCellExpeditionRequest(
    long ExpectedVersion,
    WorldCellId TargetCell,
    WorldPoint? Position,
    string? Note = null)
{
    public void Validate()
    {
        if (ExpectedVersion <= 0)
            throw new InvalidOperationException("An expected expedition version is required.");
        if (Position is null)
            throw new InvalidOperationException("An exact spatial position is required for cell repositioning.");
        if (Note is { Length: > 2000 })
            throw new InvalidOperationException("Repositioning note exceeds 2000 characters.");
    }
}

public sealed record ResolveCellEncounterRequest(
    long ExpectedVersion,
    string? ResultNote = null)
{
    public void Validate()
    {
        if (ExpectedVersion <= 0)
            throw new InvalidOperationException("An expected expedition version is required.");
        if (ResultNote is { Length: > 2000 })
            throw new InvalidOperationException("Encounter resolution note exceeds 2000 characters.");
    }
}
